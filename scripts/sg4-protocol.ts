  const participantIndices = repeated(chunkSize, (index) => decimal(index - 1n));
  const participantWeights = repeated(chunkSize, () => decimal(CHUNK_WEIGHT));
  const oraclePreState = { ...preState, readiness: true, acceptedTicketReady: true };
