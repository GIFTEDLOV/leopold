function allocationFor(circuitDefinition: CircuitDefinition) {
  if (circuitDefinition.classification === "public-decryption") return BUILDER_ALLOCATIONS.public;
  if (circuitDefinition.classification === "composite" || circuitDefinition.classification === "winner-chunk") {
    return BUILDER_ALLOCATIONS.composite;
  }
  return BUILDER_ALLOCATIONS.primitive;
}

function requiresSetup(circuitId: string): boolean {
  return (
    circuitId === "PRIZE_OR_ZERO" ||
    circuitId === "WINNER_STEP_128" ||
    circuitId.startsWith("WINNER_CHUNK_") ||
    circuitId.startsWith("COMPOSITE_DRAW_AND_CHUNK_")
  );
}

function buildRunPlan() {
  const records: Array<Record<string, string | boolean | null>> = [];
  for (const allocationIndex of [0, 1, 2] as const) {
    for (const entry of BUILDER_CIRCUITS) {
      const allocation = allocationFor(entry)[allocationIndex];
      for (const vectorId of entry.vectorIds) {
        const make = (classification: "WARMUP" | "MEASURED", index: bigint) => {
          const runId = `${PROTOCOL_VERSION}:${allocation.windowId}:${entry.id}:${vectorId}:${classification}:${decimal(index)}`;
          const winnerInstance = BUILDER_WINNER_INSTANCES.find(
            (instance) => instance.circuitId === entry.id && instance.id === vectorId,
          );
          const prizeSetupId = entry.id === "PRIZE_OR_ZERO" ? (vectorId === "WINNER_TRUE" ? "7" : "8") : null;
          const setupRequired = requiresSetup(entry.id);
          return {
            protocolVersion: PROTOCOL_VERSION,
            circuitId: entry.id,
            vectorId,
            semanticVectorId: winnerInstance?.semanticVectorId ?? vectorId,
            windowId: allocation.windowId,
            classification,
            repetitionIndex: decimal(index),
            runId,
            setupBefore: setupRequired,
            setupRecordId: setupRequired
              ? `setup-${allocation.windowId}:${entry.id}:${vectorId}:${classification}:${decimal(index)}`
              : null,
            setupDefinitionId: winnerInstance?.setupId ?? prizeSetupId,
            preStateId: winnerInstance?.preStateId ?? null,
            preStateDefinitionId: winnerInstance?.preStateId ?? null,
            expectedPostStateId: winnerInstance?.expectedPostStateId ?? null,
            expectedPostStateDefinitionId: winnerInstance?.expectedPostStateId ?? null,
            participantVectorInstanceId: winnerInstance?.participantVectorInstanceId ?? null,
            chunkSize: winnerInstance?.chunkSize ?? null,
            stateEquivalenceClass: winnerInstance?.id ?? (entry.id === "PRIZE_OR_ZERO" ? vectorId : null),
            sequenceClassification: "INDEPENDENT_PERFORMANCE_SAMPLE",
            inheritsPriorRunId: null,
            includedInVerdictStatistics: classification === "MEASURED",
          };
        };
        const warmups = repeated(allocation.warmups, (index) => make("WARMUP", index));
        const measured = repeated(allocation.measured, (index) => make("MEASURED", index));
        records.push(...warmups, ...measured);
      }
    }
  }
  return records;
}

