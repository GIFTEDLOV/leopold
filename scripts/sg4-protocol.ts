function expectedRunFields(
  entry: CircuitDefinition,
  vectorId: string,
  windowId: string,
  classification: "WARMUP" | "MEASURED",
  repetitionIndex: bigint,
): Record<string, string | boolean | null> {
  const runId = `${PROTOCOL_VERSION}:${windowId}:${entry.id}:${vectorId}:${classification}:${decimal(repetitionIndex)}`;
  const winnerInstance = EXPECTED_WINNER_INSTANCES.find(
    (instance) => instance.circuitId === entry.id && instance.id === vectorId,
  );
  const prizeSetupId = entry.id === "PRIZE_OR_ZERO" ? (vectorId === "WINNER_TRUE" ? "7" : "8") : null;
  const setupRequired =
    entry.id === "PRIZE_OR_ZERO" ||
    entry.id === "WINNER_STEP_128" ||
    entry.id === "WINNER_CHUNK_1" ||
    entry.id === "WINNER_CHUNK_4" ||
    entry.id === "WINNER_CHUNK_8" ||
    entry.id === "WINNER_CHUNK_16" ||
    entry.id === "WINNER_CHUNK_32" ||
    entry.id === "COMPOSITE_DRAW_AND_CHUNK_8" ||
    entry.id === "COMPOSITE_DRAW_AND_CHUNK_32";
  return {
    protocolVersion: PROTOCOL_VERSION,
    circuitId: entry.id,
    vectorId,
    semanticVectorId: winnerInstance?.semanticVectorId ?? vectorId,
    windowId,
    classification,
    repetitionIndex: decimal(repetitionIndex),
    runId,
    setupBefore: setupRequired,
    setupRecordId: setupRequired
      ? `setup-${windowId}:${entry.id}:${vectorId}:${classification}:${decimal(repetitionIndex)}`
      : null,
    setupDefinitionId: winnerInstance?.setupId ?? prizeSetupId,
    preStateId: winnerInstance?.preStateId ?? null,
    preStateDefinitionId: winnerInstance?.preStateId ?? null,
    expectedPostStateId: winnerInstance?.expectedPostStateId ?? null,
    expectedPostStateDefinitionId: winnerInstance?.expectedPostStateId ?? null,
    participantVectorInstanceId: winnerInstance?.participantVectorInstanceId ?? null,
    chunkSize: winnerInstance?.chunkSize ?? null,
    stateEquivalenceClass: winnerInstance?.id ?? (entry.id === "PRIZE_OR_ZERO" ? vectorId : null),
    sequenceClassification: "INDEPENDENT_PERFORMANCE_SAMPLE",
    inheritsPriorRunId: null,
    includedInVerdictStatistics: classification === "MEASURED",
  };
}

export function independentlyDeriveExpectedRunPlan(): Array<Record<string, string | boolean | null>> {
  const expected: Array<Record<string, string | boolean | null>> = [];
  for (let windowIndex = 0; windowIndex < EXPECTED_WINDOWS.length; windowIndex++) {
    for (const entry of EXPECTED_CIRCUITS) {
      const table =
        entry.repetitionCategory === "PUBLIC_DECRYPTION"
          ? EXPECTED_ALLOCATIONS.public
          : entry.repetitionCategory === "COMPOSITE_OR_WINNER_CHUNK"
            ? EXPECTED_ALLOCATIONS.composite
            : EXPECTED_ALLOCATIONS.primitive;
      const pairTable =
        entry.repetitionCategory === "PUBLIC_DECRYPTION"
          ? EXPECTED_PUBLIC_DECRYPTION_PAIRS
          : entry.repetitionCategory === "COMPOSITE_OR_WINNER_CHUNK"
            ? EXPECTED_COMPOSITE_CHUNK_PAIRS
            : EXPECTED_PRIMITIVE_PAIRS;
      const allocation = table[windowIndex];
      invariant(allocation.windowId === EXPECTED_WINDOWS[windowIndex], "closed allocation window drift");
      const expectedPairs = pairTable.filter(({ circuitId }) => circuitId === entry.id);
      for (const { vectorId } of expectedPairs) {
        for (let repetition = 1n; repetition <= allocation.warmups; repetition++) {
          expected.push(expectedRunFields(entry, vectorId, allocation.windowId, "WARMUP", repetition));
        }
        for (let repetition = 1n; repetition <= allocation.measured; repetition++) {
          expected.push(expectedRunFields(entry, vectorId, allocation.windowId, "MEASURED", repetition));
        }
      }
    }
  }
  return expected;
}

