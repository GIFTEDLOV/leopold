export type Protocol = ReturnType<typeof buildProtocol>;

function invariant(condition: boolean, message: string): asserts condition {
  if (!condition) throw new Error(`SG4 protocol invariant failed: ${message}`);
}

function decimal(value: bigint): string {
  return value.toString(10);
}

function repeated<T>(count: bigint, factory: (index: bigint) => T): T[] {
  const result: T[] = [];
  for (let index = 1n; index <= count; index++) result.push(factory(index));
  return result;
}

function deepFreeze<T>(value: T): T {
  if (value !== null && typeof value === "object" && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}

export function rejectionPlan(total: bigint) {
  invariant(total >= 0n && total <= T_MAX, "rejection total outside locked domain");
  if (total === 0n) {
    return {
      total: "0",
      noDraw: true,
      quotient: null,
      remainder: null,
      rejectionLimit: null,
      allCandidatesValid: false,
    };
  }
  const quotient = CANDIDATE_DOMAIN_SIZE / total;
  const remainder = CANDIDATE_DOMAIN_SIZE % total;
  return {
    total: decimal(total),
    noDraw: false,
    quotient: decimal(quotient),
    remainder: decimal(remainder),
    rejectionLimit: decimal(quotient * total),
    allCandidatesValid: remainder === 0n,
  };
}

export function nearestRankP90Index(sampleCount: bigint): bigint {
  invariant(sampleCount > 0n, "p90 requires a sample");
  return (9n * sampleCount + 9n) / 10n - 1n;
}

export function exactMean(values: readonly bigint[]): { numerator: string; denominator: string } {
  invariant(values.length > 0, "mean requires a sample");
  let numerator = 0n;
  for (const value of values) {
    invariant(value >= 0n, "metric samples must be non-negative");
    numerator += value;
  }
  return { numerator: decimal(numerator), denominator: decimal(BigInt(values.length)) };
}

export function projectSequentialCompletion(
  participants: bigint,
  chunkSize: bigint,
  p90ChunkLatencyMilliseconds: bigint,
) {
  invariant(participants > 0n && chunkSize > 0n && p90ChunkLatencyMilliseconds >= 0n, "invalid projection input");
  const transactions = (participants + chunkSize - 1n) / chunkSize;
  return {
    participants: decimal(participants),
    transactions: decimal(transactions),
    projectedMilliseconds: decimal(transactions * p90ChunkLatencyMilliseconds),
  };
}

