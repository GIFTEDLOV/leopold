export function deriveProtocol(): Protocol {
  const protocol = buildProtocol();
  validateProtocol(protocol);
  return protocol;
}

export function serializeProtocol(): string {
  return `${JSON.stringify(deriveProtocol(), null, 2)}\n`;
}

